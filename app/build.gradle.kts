import java.util.Properties

/**
 * Release signing is configured from `keystore.properties` in the repo root —
 * a file that is gitignored and never committed. Without it the release build
 * still works, but falls back to the debug key and is NOT distributable.
 *
 * keystore.properties:
 *   storeFile=C:/path/to/jellyflix-release.jks
 *   storePassword=...
 *   keyAlias=jellyflix
 *   keyPassword=...
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = keystoreProperties.getProperty("storeFile") != null

